<h1>How Long Does Artificial Turf Installation Take?</h1>

<p><strong>A typical backyard turf installation takes <?= fact('timeline_typical') ?>.</strong> Size, access, weather and base work decide where yours falls.</p>

<h2>What each stage looks like</h2>
<ol>
    <li><strong>Removal and excavation.</strong> Existing grass and material out, dug to depth.</li>
    <li><strong>Base.</strong> Spread, graded and compacted in layers. This is the stage you don't want rushed.</li>
    <li><strong>Turf.</strong> Laid, cut, seamed and secured.</li>
    <li><strong>Infill and finish.</strong> Infill spread, turf brushed, final walk-through.</li>
</ol>

<h2>What slows it down</h2>
<ul>
    <li><strong>Rain.</strong> A wet base can't be compacted properly. We wait.</li>
    <li><strong>Access.</strong> Narrow gates mean material moves by hand.</li>
    <li><strong>Drainage fixes.</strong> Regrading takes longer than a flat yard.</li>
    <li><strong>HOA approval.</strong> This happens before install, but it's usually the longest part of the calendar.</li>
    <li><strong>Size and shape.</strong> Curves and multiple areas take more time.</li>
</ul>

